def frame_to_ascii(img: Image.Image, cols: int = 100, rows: int = 36) -> str:
    """
    Кадр -> символьная карта. Сопоставление БЛИЖАЙШИМ цветом палитры,
    а не первым попавшим в допуск.

    Регрессия, из-за которой переписано: при first-match-wins тёмный пол
    гаража (28,32,42) попадал в допуск чернил (26,22,24) и нижняя треть
    кадра превращалась в сплошную стену '#'. Порядок записей в палитре
    молча определял картинку, и добавление нового цвета ломало старые
    сцены. Ближайший цвет однозначен и от порядка не зависит; допуск
    остаётся только как радиус «дальше этого — считаем фоном».
    """
    small = img.resize((cols, rows), Image.NEAREST).convert("RGB")
    px = small.load()
    lines = []
    for y in range(rows):
        row = []
        for x in range(cols):
            r, g, b = px[x, y]
            best_c, best_d = ".", None
            for (pr, pg, pb), tol, c in PALETTE:
                d2 = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
                if d2 <= tol * tol * 3 and (best_d is None or d2 < best_d):
                    best_c, best_d = c, d2
            row.append(best_c)
        lines.append("".join(row))
    return "\n".join(lines)


def describe(img: Image.Image) -> dict:
    """Числовой отчёт: центры масс цветовых групп. Для проверок вида
    «голова выше туловища», «банка правее героя»."""
    import numpy as np
    a = np.asarray(img.convert("RGB")).astype(int)
    out = {}
    for (pr, pg, pb), tol, c in PALETTE:
        mask = ((abs(a[:, :, 0] - pr) <= tol) & (abs(a[:, :, 1] - pg) <= tol)
                & (abs(a[:, :, 2] - pb) <= tol))
        n = int(mask.sum())
        if n < 10:
            continue
        ys, xs = mask.nonzero()
        key = c if c not in out else None
        if key:
            out[key] = {"px": n, "cx": round(float(xs.mean()), 1),
                        "cy": round(float(ys.mean()), 1),
                        "top": int(ys.min()), "bottom": int(ys.max()),
                        "left": int(xs.min()), "right": int(xs.max())}
    return out
